// Markers delimiting the generated command reference in SKILL.md and
// README.md. scripts/build-docs.go rewrites everything between them.
const (
	ReferenceStart = "<!-- cli-reference:start -->"
	ReferenceEnd   = "<!-- cli-reference:end -->"
)

// referenceLogOptions stands in for the shared log flags (logFlags) in the
// generated reference, which would otherwise repeat on every logs command.
const referenceLogOptions = "[LOG-OPTIONS]"

// ReferenceMarkdown renders every visible command of the CLI as one code
// block: a line per command with all of its arguments and flags, and the
// description as a trailing comment. It is generated from the command
// definitions, so the docs cannot drift from the code.
func ReferenceMarkdown() string {
	app := buildApp()
	skip := map[string]bool{"help": true}
	for _, f := range perCommandFlags {
		for _, n := range f.Names() {
			skip[n] = true
		}
	}

	var b strings.Builder
	b.WriteString("Generated by `make build-docs`; do not edit by hand. `[...]` is optional and `<...>` is a value.\n")
	b.WriteString("`LOG-OPTIONS` is `" + logOptionsSummary() + "`.\n\n")
	b.WriteString("```bash\n")
	b.WriteString("# global options: --api-url <string>, --api-token|--api-key <string>, --log-level <string>, --local, --dev, --debug\n")
	// Commands with subcommands form their own block; consecutive single
	// commands share one. Comments are aligned within a block.
	var blocks [][][2]string
	previousSingle := false
	for _, cmd := range app.Commands {
		if cmd.Hidden || skip[cmd.Name] {
			continue
		}
		var lines [][2]string
		collectReference(&lines, "futrou", cmd, skip)
		single := len(lines) == 1
		if single && previousSingle {
			blocks[len(blocks)-1] = append(blocks[len(blocks)-1], lines...)
		} else {
			blocks = append(blocks, lines)
		}
		previousSingle = single
	}
	for _, lines := range blocks {
		width := 0
		for _, line := range lines {
			if n := len(line[0]); n > width && n <= referenceMaxWidth {
				width = n
			}
		}
		b.WriteString("\n")
		for _, line := range lines {
			b.WriteString(line[0])
			if line[1] != "" {
				pad := width - len(line[0])
				if pad < 0 {
					pad = 0
				}
				b.WriteString(strings.Repeat(" ", pad) + "  # " + line[1])
			}
			b.WriteString("\n")
		}
	}
	b.WriteString("```\n")
	return b.String()
}

// referenceMaxWidth is the longest command line that still takes part in the
// comment alignment; longer ones just get their comment after two spaces.
const referenceMaxWidth = 100

// logOptionsSummary lists the shared log flags.
func logOptionsSummary() string {
	var parts []string
	for _, flag := range logFlags {
		parts = append(parts, flagSyntax(flag, true))
	}
	return strings.Join(parts, " ")
}

// collectReference appends a (command line, description) pair for cmd, when
// it can be run, and for each of its visible subcommands.
func collectReference(lines *[][2]string, parent string, cmd *cli.Command, skip map[string]bool) {
	path := parent + " " + cmd.Name
	if len(cmd.Aliases) > 0 {
		path += "|" + strings.Join(cmd.Aliases, "|")
	}
	if len(cmd.Subcommands) == 0 || cmd.Action != nil {
		line := path
		if cmd.ArgsUsage != "" {
			line += " " + cmd.ArgsUsage
		}
		line += commandFlags(cmd.Flags, skip)
		*lines = append(*lines, [2]string{line, cmd.Usage})
	}
	for _, sub := range cmd.Subcommands {
		if sub.Hidden || skip[sub.Name] {
			continue
		}
		collectReference(lines, parent+" "+cmd.Name, sub, skip)
	}
}

// commandFlags renders the flags of a command; the shared log flags are
// collapsed into referenceLogOptions.
func commandFlags(flags []cli.Flag, skip map[string]bool) string {
	logNames := map[string]bool{}
	for _, f := range logFlags {
		logNames[f.Names()[0]] = true
	}
	hasLog := 0
	for _, f := range flags {
		if logNames[f.Names()[0]] {
			hasLog++
		}
	}
	collapse := hasLog == len(logFlags)

	var out string
	for _, flag := range flags {
		names := flag.Names()
		if len(names) == 0 || skip[names[0]] {
			continue
		}
		if hidden, ok := flag.(interface{ IsVisible() bool }); ok && !hidden.IsVisible() {
			continue
		}
		if collapse && logNames[names[0]] {
			continue
		}
		required := false
		if req, ok := flag.(cli.RequiredFlag); ok {
			required = req.IsRequired()
		}
		out += " " + flagSyntax(flag, !required)
	}
	if collapse {
		out += " " + referenceLogOptions
	}
	return out
}

// flagSyntax renders one flag as "--name|-n <string>", in brackets when it is
// optional.
func flagSyntax(flag cli.Flag, optional bool) string {
	var forms []string
	for _, n := range flag.Names() {
		if len(n) == 1 {
			forms = append(forms, "-"+n)
		} else {
			forms = append(forms, "--"+n)
		}
	}
	// Long names first: "--file|-f".
	sort.SliceStable(forms, func(i, j int) bool { return strings.HasPrefix(forms[i], "--") && !strings.HasPrefix(forms[j], "--") })
	out := strings.Join(forms, "|")
	switch flag.(type) {
	case *cli.StringFlag:
		out += " <string>"
	case *cli.IntFlag:
		out += " <int>"
	case *cli.Float64Flag:
		out += " <number>"
	case *cli.StringSliceFlag:
		out += " <string>..."
	case *cli.BoolFlag:
		if f := flag.(*cli.BoolFlag); f.Value {
			out += "=false"
		}
	}
	if optional {
		return "[" + out + "]"
	}
	return out
}

// ExampleFiles are the example configs embedded in the docs, with the code
// fence language used for each.
var ExampleFiles = []struct{ Name, Language string }{
	{"futrou.json", "json"},
	{"futrou.yaml", "yaml"},
	{"futrou.mjs", "js"},
}

// ExampleMarkers returns the markers delimiting the embedded example file.
func ExampleMarkers(name string) (start, end string) {
	return "<!-- example:" + name + ":start -->", "<!-- example:" + name + ":end -->"
}

// ReplaceExample returns doc with the text between the markers of the named
// example replaced by a code block holding content. A doc without those
// markers is returned unchanged.
func ReplaceExample(doc, name, language, content string) string {
	startMarker, endMarker := ExampleMarkers(name)
	start := strings.Index(doc, startMarker)
	end := strings.Index(doc, endMarker)
	if start < 0 || end < start {
		return doc
	}
	block := "```" + language + "\n" + strings.TrimRight(content, "\n") + "\n```"
	return doc[:start+len(startMarker)] + "\n\n" + block + "\n\n" + doc[end:]
}

// ReplaceReference returns doc with the text between the reference markers
// replaced by reference.
func ReplaceReference(doc, reference string) (string, error) {
	start := strings.Index(doc, ReferenceStart)
	end := strings.Index(doc, ReferenceEnd)
	if start < 0 || end < start {
		return "", fmt.Errorf("missing %s ... %s markers", ReferenceStart, ReferenceEnd)
	}
	return doc[:start+len(ReferenceStart)] + "\n\n" + reference + "\n" + doc[end:], nil
}
